using System;
using System.Linq.Expressions;
using System.Threading.Tasks;
using GtMotive.Estimate.Microservice.Domain.Fleets;
using GtMotive.Estimate.Microservice.Domain.Vehicles;

namespace GtMotive.Estimate.Microservice.ApplicationCore.Queries
{
    /// <summary>
    /// Read port for vehicle queries. It does not load aggregates nor use the unit of work.
    /// </summary>
    public interface IVehicleQueries
    {
        /// <summary>
        /// Gets a page of the vehicles of a fleet.
        /// </summary>
        /// <param name="fleetId">Fleet id.</param>
        /// <param name="status">Status filter.</param>
        /// <param name="admission">Predicate generated by the fleet admission policy.</param>
        /// <param name="page">Page number (1-based).</param>
        /// <param name="pageSize">Page size.</param>
        /// <returns>The page.</returns>
        Task<PageResult<VehicleModel>> GetPage(
            FleetId fleetId,
            VehicleStatus status,
            Expression<Func<VehicleModel, bool>> admission,
            int page,
            int pageSize);
    }
}
